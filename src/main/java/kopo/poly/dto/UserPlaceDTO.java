package kopo.poly.dto;

import lombok.Getter;
import lombok.Setter;

/**
 * 사용자가 등록해둔 장소 한 곳. 지도 왼쪽 위 '집 / 회사 / 자주가는 경로' 버튼이 가리키는 값이다.
 *
 * <p><b>왜 필요한가</b>: 챗봇이 "집에서 출발"을 기본 전제로 삼는데 그 값이 아무데도 없었다.
 * 버튼은 8/9부터 화면에 있었지만 눌러도 '로그인 기능이 붙은 뒤에 쓸 수 있습니다' 한 줄만 나왔다.
 *
 * <p><b>★ 이 표는 주소가 아니라 좌표를 들고 있는 표다.</b> 카카오 우편번호 API 는 좌표를 주지
 * 않으므로 등록하는 그 순간 주소검색 API 로 한 번 변환해 박는다. 주소만 저장해두면 집 버튼을
 * 누를 때마다 카카오를 불러야 하고 — 느리고, 한도를 먹고, 카카오가 잠깐 죽으면 집 버튼이 같이 죽는다.
 * {@link #address} 는 사람이 "어디로 등록했더라" 를 확인하려고 남기는 것이지 길찾기의 입력이 아니다.
 */
@Getter
@Setter
public class UserPlaceDTO {

    private long id;

    /** 등록한 사람. 남의 장소를 못 건드리게 조회·수정·삭제 조건에 항상 함께 들어간다. */
    private String username;

    /**
     * {@code HOME} / {@code WORK} / {@code FAV}.
     *
     * <p>집·회사는 사용자당 하나다. 그 제약은 컬럼이 아니라
     * {@code UQ_USER_PLACES(USERNAME, PLACE_TYPE, LABEL)} 과, 앱이 {@link #label} 을
     * '집'·'회사'로 고정해 넣는 것이 함께 만든다. {@code FAV} 만 라벨이 달라 여러 개가 된다.
     */
    private String placeType;

    /**
     * 화면에 뜨는 이름.
     *
     * <p>좌표만 저장하면 화면에 '집' 이라고만 뜨고 그게 실제로 어디인지 확인할 방법이 사라진다.
     */
    private String label;

    /**
     * 우편번호({@code data.zonecode}). <b>표시용이다.</b>
     *
     * <p>{@link #address} 와 <b>따로 저장한다.</b> 합쳐서 "(28644)충북 청주시…" 로 두면
     * 우편번호만 따로 쓰고 싶을 때 다시 잘라내야 하고, 좌표 변환에도 군더더기가 섞인다.
     *
     * <p>★ 처음에는 "괄호를 붙이면 주소검색이 0건을 낸다"고 적어뒀는데 <b>재보니 틀렸다.</b>
     * 2026-08-21 청주 도로명·지번 8가지로 재봤더니 괄호를 붙이든 안 붙이든 전부 같은 좌표가
     * 나왔다. 그래도 원문만 넘기는 쪽을 유지한다 — 우편번호는 좌표에 아무것도 보태지 않고,
     * 모든 주소에서 견딘다는 보장도 없다. 다만 <b>0건이 되는 것은 아니다.</b>
     */
    private String zonecode;

    /** {@code data.address} 원문. <b>좌표 변환의 입력이 되는 값이라 손대지 않고 그대로 저장한다.</b> */
    private String address;

    /**
     * 동·호수. 표시용이고 좌표에 영향이 없다.
     *
     * <p>좌표는 건물까지가 한계라 상세주소를 붙여도 정확도가 오르지 않는다(재봤다 — 붙여도
     * 같은 좌표가 나온다. 방해가 되는 것도 아니고 그냥 무의미하다).
     * 이 표에서 개인정보 성격이 가장 강한 칸이기도 해서, 좌표 변환에 굳이 실어 보내지 않는다.
     */
    private String addressDetail;

    /** 등록 시점에 주소검색으로 한 번 변환해 박은 값. 길찾기가 쓰는 것은 이쪽이다. */
    private Double latitude;
    private Double longitude;

    /**
     * 어느 서브그래프에 속하는가. 등록하는 그 자리에서 판정해 박는다.
     *
     * <p>범위 밖 주소를 그냥 받으면 등록은 조용히 성공하고 한참 뒤 길찾기에서 실패한다 —
     * 원인과 증상이 멀리 떨어진, 제일 찾기 나쁜 형태다.
     *
     * <p>{@code region-id} 를 갈아타면(보은 ↔ 청주) 남의 지역 장소가 그대로 남는데
     * <b>지우지 않는다.</b> 지역은 되돌아올 수 있고 주소는 다시 못 받는다. 안내만 막는다.
     */
    private String regionId;

    /** {@code yyyy-MM-dd HH:mm} 문자열. 화면에 그대로 찍으려는 것이라 날짜 연산을 하지 않는다. */
    private String createdAt;
    private String updatedAt;

    /**
     * 이 장소가 지금 안내 중인 지역에 있는가. DB 컬럼이 아니라 조회 뒤 서비스가 채운다.
     *
     * <p>화면이 '집(보은) — 지금은 청주를 안내 중입니다' 처럼 <b>왜 못 쓰는지</b>를
     * 말할 수 있어야 한다. 그냥 안 보여주면 사용자는 등록이 지워진 줄 안다.
     */
    private boolean usable;
}
