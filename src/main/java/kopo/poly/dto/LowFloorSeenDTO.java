package kopo.poly.dto;

/**
 * 도착정보에서 저상차를 본 기록 한 줄. {@code BUS_LOW_FLOOR_SEEN} 의 한 행이다.
 *
 * <p><b>왜 저장하는가</b>: 이 관측이 메모리에만 있으면 재기동할 때마다 비고,
 * 그동안 <b>저상 정류장 표가 통째로 없다.</b> 그러면 '걸어가서 탈 수 있는 정류장'도
 * 복합 경로도 몇십 초 동안 아무 답을 못 한다 — 화면에는 '저상버스가 서는 정류장이 없습니다'
 * 라고 뜨는데, 그건 사실이 아니라 아직 안 쌓인 것이다.
 *
 * <p><b>지역이 열쇠에 들어가는 이유</b>: 노선번호는 지역마다 겹친다. 청주에도 보은에도
 * 100번이 있을 수 있어서, 번호만으로 잡으면 다른 지역에서 본 저상차를 이 지역 것으로 센다.
 *
 * @param regionId 지역
 * @param routeNo  노선번호. {@code 40-2} 처럼 하이픈이 있어 문자열이다
 * @param lowCnt   저상차로 관측된 횟수. <b>1 이상이면 저상 노선으로 본다</b> —
 *                 비율을 따지지 않는 이유는 답하려는 것이 '저상차가 다니기는 하는가' 라서다
 * @param totalCnt 저상/일반을 가린 전체 관측 횟수. 지금은 안 쓰지만 <b>분모 없이 쌓으면
 *                 되돌릴 수 없어서</b> 같이 센다(나중에 '10대 중 1대만 저상' 안내를 하려면 필요하다)
 */
public record LowFloorSeenDTO(String regionId,
                              String routeNo,
                              int lowCnt,
                              int totalCnt) {
}
